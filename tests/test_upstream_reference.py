"""Behavior checks against golden outputs captured with the pinned tinker-cookbook.

The reference JSON is not regenerated by pytest.
"""

import asyncio
import json
from pathlib import Path

import pytest
from reference_cases import (
    DEFAULT_RENDERER,
    RENDERERS,
    ROLLOUT_CASES,
    FixedTokenizer,
    renderer_snapshot,
    rollout_snapshot,
)

from search_r1.backends.completers import TokensWithLogprobs
from search_r1.env.limits import RolloutLimits
from search_r1.env.renderers import get_renderer
from search_r1.env.renderers.base import RendererError, ToolCall
from search_r1.env.rollout import do_single_rollout
from search_r1.env.search_tool_env import build_search_env, search_tool_spec
from search_r1.env.tools import BM25Tool, TextAnswerReward

REFERENCE = json.loads((Path(__file__).parent / "fixtures/cookbook_reference.json").read_text())


@pytest.mark.parametrize("name", RENDERERS)
def test_renderer_matches_pinned_reference(name):
    tokenizer = FixedTokenizer()
    renderer = get_renderer(name, tokenizer)
    actual = renderer_snapshot(renderer, ToolCall, search_tool_spec(False))
    assert actual == REFERENCE["renderers"][name]
    assert tokenizer.backend_tokenizer.encode_special_tokens is False


@pytest.mark.parametrize("limited", [False, True])
def test_tool_schema_matches_pinned_reference(limited):
    assert search_tool_spec(limited) == REFERENCE["tool_specs"][str(limited)]


def local_rollout(case, **kwargs):
    return rollout_snapshot(
        case,
        build_env=build_search_env,
        renderer=get_renderer(DEFAULT_RENDERER, FixedTokenizer()),
        reward_cls=TextAnswerReward,
        retriever_cls=BM25Tool,
        token_result_cls=TokensWithLogprobs,
        **kwargs,
    )


@pytest.mark.parametrize("case", ROLLOUT_CASES)
def test_rollout_matches_pinned_reference(case):
    assert (
        asyncio.run(local_rollout(case, run_rollout=do_single_rollout))
        == REFERENCE["rollouts"][case]
    )


@pytest.mark.parametrize("name", RENDERERS)
@pytest.mark.parametrize(
    "part", [{"type": "image", "image": "unused"}, {"type": "audio", "audio": b""}]
)
def test_renderers_reject_unsupported_multimodal_input(name, part):
    renderer = get_renderer(name, FixedTokenizer())
    with pytest.raises(RendererError, match="text only"):
        renderer.build_generation_prompt([{"role": "user", "content": [part]}])


def test_runner_refuses_unimplemented_budget_mode():
    class Env:
        rollout_limits = RolloutLimits(max_turns=1)

    with pytest.raises(ValueError, match="rollout_limits are unsupported"):
        asyncio.run(do_single_rollout(None, Env()))
